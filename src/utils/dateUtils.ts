export function generateCalendarDays(year: number, month: number, selectedDate: Date, transactionDates: Set<string>): DayCell[] {
  const currentMonth = new Date(year, month - 1, 1);
  const start = startOfWeek(startOfMonth(currentMonth), { weekStartsOn: 0 });
  const end = endOfWeek(endOfMonth(currentMonth), { weekStartsOn: 0 });
  const days = eachDayOfInterval({ start, end });
  const today = new Date();

  return days.map((day) => {
    const fd = format(day, 'yyyy-MM-dd');
    const m = day.getMonth() + 1;
    const d = day.getDate();
    const lunarKey = `${m}-${d}`;
    return {
      date: d,
      fullDate: fd,
      lunar: lunarMap[lunarKey] || '',
      isCurrentMonth: isSameMonth(day, currentMonth),
      isToday: isSameDay(day, today),
      isSelected: isSameDay(day, selectedDate),
      hasTransaction: transactionDates.has(fd),
    };
  });
}

export function getMonthTitle(year: number, month: number): string {
  return `${year}年${month}月`;
}

export function getWeekdayName(dateStr: string): string {
  const weekdays = ['周日', '周一', '周二', '周三', '周四', '周五', '周六'];
  return weekdays[new Date(dateStr).getDay()];
}

